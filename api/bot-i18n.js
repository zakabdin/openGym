// Every pack falls back to English key by key, so a missing string is never a blank message.
export const PACKS = { en, de, es, fr, it, 'pt-BR': ptBR, pl, tr: trTR, ru, uk, zh, ko, hi, hu, th, ar, az }
const ALIAS = { 'de-CH': 'de', pt: 'pt-BR' }

export const LANG_NAMES = {
  en: 'English', de: 'Deutsch', es: 'Español', fr: 'Français', it: 'Italiano', pt: 'Português (Portugal)',
  'pt-BR': 'Português (Brasil)', pl: 'Polski', tr: 'Türkçe', ru: 'Русский', uk: 'Українська', zh: '中文',
  ko: '한국어', hi: 'हिन्दी', th: 'ไทย', hu: 'Magyar', ar: 'العربية', az: 'Azərbaycanca'
}
// The app's own language codes, for the /language command.
export const LANG_CODES = Object.keys(LANG_NAMES)

/** A language tag ('pt-BR', 'pt_br', 'de-AT', 'zh-hans') as one of the app's codes, or null. */
export function matchLang(tag) {
  if (typeof tag !== 'string') return null
  const want = tag.trim().replace(/_/g, '-').toLowerCase()
  if (!want) return null
  const exact = LANG_CODES.concat('de-CH').find(k => k.toLowerCase() === want)
  if (exact) return exact
  const base = want.split('-')[0]
  return LANG_CODES.includes(base) ? base : null
}

/**
 * The message for `key` in `lang`, `{0}`… filled from `args`. A message written "one|many" (English
 * only, where the noun changes) takes its first half when the first argument is 1.
 */
export function tr(lang, key, ...args) {
  const code = ALIAS[lang] || lang
  const pack = PACKS[code] || en
  let s = pack[key] ?? en[key] ?? key
  if (s.includes('|')) { const [one, many] = s.split('|'); s = +args[0] === 1 ? one : many }
  return s.replace(/\{(\d+)\}/g, (m, i) => (args[+i] ?? ''))
}

